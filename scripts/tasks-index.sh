#!/usr/bin/env bash
# Regenerates tasks/INDEX.md from task frontmatter and checks that depends_on forms a DAG.
# Usage: scripts/tasks-index.sh [--check]   (--check fails if INDEX.md is stale)
set -euo pipefail
export LC_ALL=C # technical: byte-order sort and compare, so T-102 < T-102a < T-103 on every machine
cd "$(dirname "$0")/.."

tmp="$(mktemp)"
trap 'rm -f "$tmp" "$tmp.rows"' EXIT

# One TSV row per task: id, milestone, status, size, depends_on, title, path
for f in tasks/M*/T-*.md; do
  awk -v path="$f" '
    NR == 1 && $0 != "---" { exit 1 }
    NR > 1 && $0 == "---" { done = 1; exit }
    /^id:/            { sub(/^id: */, ""); id = $0 }
    /^title:/         { sub(/^title: */, ""); title = $0 }
    /^milestone:/     { sub(/^milestone: */, ""); ms = $0 }
    /^status:/        { sub(/^status: */, ""); sub(/ *#.*/, ""); st = $0 }
    /^estimated_size:/{ sub(/^estimated_size: */, ""); sz = $0 }
    /^depends_on:/    { sub(/^depends_on: *\[/, ""); sub(/\].*/, ""); gsub(/ /, ""); dep = $0 }
    END { if (!done || id == "") { print "bad frontmatter: " path > "/dev/stderr"; exit 1 }
          printf "%s\t%s\t%s\t%s\t%s\t%s\t%s\n", id, ms, st, sz, dep, title, path }
  ' "$f"
done | sort > "$tmp.rows"

# DAG + reference checks (every dependency exists and has a lower ID; no size L),
# valid statuses, and WIP = 1 (at most one task in_progress; WORKFLOW.md §2)
awk -F'\t' '
  BEGIN { split("draft todo in_progress blocked review changes_requested done", v, " "); for (i in v) valid[v[i]] = 1 }
  { ids[$1] = 1; deps[$1] = $5; size[$1] = $4
    if (!($3 in valid)) { print $1 ": unknown status " $3 > "/dev/stderr"; badst = 1 }
    if ($3 == "in_progress") { wip++; wipids = wipids " " $1 } }
  END {
    bad = badst
    if (wip > 1) { print "WIP limit: more than one task in_progress:" wipids > "/dev/stderr"; bad = 1 }
    for (id in deps) {
      if (size[id] == "L") { print "size L must be split: " id > "/dev/stderr"; bad = 1 }
      n = split(deps[id], d, ",")
      for (i = 1; i <= n; i++) {
        if (d[i] == "") continue
        if (!(d[i] in ids)) { print id ": unknown dependency " d[i] > "/dev/stderr"; bad = 1 }
        else if (d[i] >= id) { print id ": dependency " d[i] " is not lower (cycle risk)" > "/dev/stderr"; bad = 1 }
      }
    }
    exit bad
  }' "$tmp.rows"

{
  echo "# Task index"
  echo
  echo "Generated by \`scripts/tasks-index.sh\` from task frontmatter. Do not edit by hand: change the status in the task file and rerun the script (WORKFLOW.md)."
  echo
  echo "| ID | Title | Milestone | Status | Size | Depends on |"
  echo "|---|---|---|---|---|---|"
  awk -F'\t' '{ gsub(/,/, ", ", $5); printf "| [%s](%s) | %s | %s | `%s` | %s | %s |\n", $1, substr($7, 7), $6, $2, $3, $4, $5 }' "$tmp.rows"
  echo
  awk -F'\t' '{ c[$3]++ } END { printf "Totals:"; for (s in c) printf " %s %d;", s, c[s]; print "" }' "$tmp.rows"
} > "$tmp"

if [[ "${1:-}" == "--check" ]]; then
  diff -u tasks/INDEX.md "$tmp" && echo "INDEX.md up to date"
else
  mv "$tmp" tasks/INDEX.md
  echo "wrote tasks/INDEX.md ($(wc -l < "$tmp.rows") tasks)"
fi
